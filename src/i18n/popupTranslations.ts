type DeepResolved<T> = {
  [K in keyof T]: T[K] extends { ar: string; en: string }
    ? string
    : T[K] extends object
    ? DeepResolved<T[K]>
    : T[K];
};

export type PopupTranslations = DeepResolved<typeof POPUP_TRANSLATIONS>;

function resolveSection<T>(obj: T, lang: LanguageCode): any {
  if (!obj || typeof obj !== 'object') return obj;
  if ('ar' in (obj as any) && 'en' in (obj as any)) {
    return lang === 'en' ? (obj as any).en : (obj as any).ar;
  }
  const result: any = Array.isArray(obj) ? [] : {};
  for (const key of Object.keys(obj as any)) {
    result[key] = resolveSection((obj as any)[key], lang);
  }
  return result;
}

export function getPopupTranslations(lang: LanguageCode): PopupTranslations {
  return resolveSection(POPUP_TRANSLATIONS, lang);
}

export function formatString(template: string, vars: Record<string, string | number>): string {
  let str = template;
  for (const [key, value] of Object.entries(vars)) {
    str = str.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value));
  }
  return str;
}
